// Generates lib/src/generated/actions.dart from the vendored API docs
// (doc/api/API-Server.en.md). Run: dart run tool/generate_actions.dart
import 'dart:io';

final _heading = RegExp(r'^### (\w+)$');
final _param = RegExp(r'^\| `([^`]+)` \| _(.*?)_ \|(.*)\|\s*$');
const _reserved = {
  'default',
  'class',
  'new',
  'in',
  'is',
  'as',
  'do',
  'if',
  'for',
  'var',
  'void',
  'with',
  'true',
  'false',
  'null',
  'this',
  'switch',
  'case',
  'enum',
};

class _Param {
  _Param(this.wire, this.type, this.optional, this.doc);
  final String wire;
  final String type;
  final bool optional;
  final String doc;
}

class _Action {
  final names = <String>[];
  String since = '';
  final description = StringBuffer();
  final params = <_Param>[];
}

String _camel(String s) {
  final parts = s.split('_');
  final out = StringBuffer(parts.first);
  for (final p in parts.skip(1)) {
    if (p.isEmpty) continue;
    out.write(p[0].toUpperCase() + p.substring(1));
  }
  var r = out.toString();
  if (_reserved.contains(r)) r = '${r}_';
  return r;
}

String _lowerFirst(String s) {
  // GetCPInfo -> getCpInfo, APPlayerAction -> apPlayerAction
  var i = 0;
  while (i < s.length &&
      s[i].toUpperCase() == s[i] &&
      s[i].toLowerCase() != s[i]) {
    i++;
  }
  if (i <= 1) return s[0].toLowerCase() + s.substring(1);
  if (i == s.length) return s.toLowerCase();
  final head = s.substring(0, i - 1).toLowerCase();
  return head + s.substring(i - 1);
}

String _dartType(String raw) {
  var t = raw.replaceAll(' (optional)', '').replaceAll('&lt;', '<');
  if (t.startsWith('String')) return 'String';
  if (t.startsWith('Boolean')) return 'bool';
  if (t.startsWith('Number')) return 'num';
  if (t.startsWith('Array')) return 'List<Object?>';
  return 'Object'; // Object / documented model: pass a JSON-encodable value
}

String _clean(String s) => s
    .replaceAll(RegExp(r'<br\s*/?>'), ' ')
    .replaceAll(RegExp(r'<[^>]+>'), '')
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>')
    .replaceAll(RegExp(r'\s+'), ' ')
    .trim();

void main() {
  final lines = File('../../docs/api/API-Server.en.md').readAsLinesSync();
  final start = lines.indexWhere((l) => l == '### GetTokenInfo');
  final end = lines.indexWhere((l) => l == '## Lyrics');
  final actions = <_Action>[];
  _Action? cur;
  var mode = '';
  var descDone = false;
  for (var i = start; i < end; i++) {
    final l = lines[i];
    final h = _heading.firstMatch(l);
    if (h != null) {
      // consecutive headings are aliases of one action
      if (cur == null || mode != 'alias') {
        cur = _Action();
        actions.add(cur);
        descDone = false;
      }
      cur.names.add(h.group(1)!);
      mode = 'alias';
      continue;
    }
    if (cur == null) continue;
    if (l.startsWith('- v')) {
      cur.since = l.substring(2).trim();
      mode = 'desc';
      continue;
    }
    if (l.startsWith('**Parameters:**')) {
      mode = 'params';
      continue;
    }
    if (l.startsWith('**Response') ||
        l.startsWith('**Example') ||
        l.startsWith('_Method does not')) {
      mode = 'other';
      continue;
    }
    if (l == '---') {
      mode = 'done';
      continue;
    }
    if (mode == 'desc' && !descDone && l.trim().isNotEmpty) {
      cur.description.write(_clean(l));
      descDone = true;
    } else if (mode == 'params') {
      final m = _param.firstMatch(l);
      if (m != null && RegExp(r'^\w+$').hasMatch(m.group(1)!)) {
        final raw = m.group(2)!;
        cur.params.add(_Param(
            m.group(1)!,
            _dartType(raw),
            raw.contains('(optional)'),
            _clean(m.group(3)!.replaceFirst(RegExp(r'^\s*'), ''))));
      }
    }
  }

  final byGroup = <String, List<String>>{};
  final catalog = <String>[];
  for (final a in actions) {
    for (final name in a.names) {
      catalog.add(name);
      byGroup.putIfAbsent(_groupOf(name), () => []).add(_method(a, name));
    }
  }

  Directory('lib/src/actions').createSync(recursive: true);
  for (final entry in byGroup.entries) {
    final cls = 'Holyrics${_pascal(entry.key)}Actions';
    final out = StringBuffer()
      ..writeln('// GENERATED by tool/generate_actions.dart.')
      ..writeln('// Do not edit by hand.')
      ..writeln()
      ..writeln('/// Raw ${entry.key.replaceAll('_', ' ')} actions of the '
          'Holyrics API Server.')
      ..writeln('///')
      ..writeln('/// Every method returns the response `data` field.')
      ..writeln('mixin $cls {')
      ..writeln('  /// Sends [action] with [params] (null values omitted).')
      ..writeln('  Future<Object?> call(String action, '
          '[Map<String, Object?>? params]);')
      ..writeln()
      ..writeln(entry.value.join('\n'))
      ..writeln('}');
    File('lib/src/actions/${entry.key}_actions.dart')
        .writeAsStringSync(out.toString());
  }

  final index = StringBuffer()
    ..writeln('// GENERATED by tool/generate_actions.dart.')
    ..writeln('// Do not edit by hand.')
    ..writeln()
    ..writeln('/// Names of every action in the vendored API docs.')
    ..writeln('const holyricsActionNames = <String>[');
  for (final n in catalog) {
    index.writeln("  '$n',");
  }
  index.writeln('];');
  File('lib/src/actions/action_names.dart').writeAsStringSync(index.toString());

  final groups = byGroup.keys.toList()..sort();
  final barrel = StringBuffer()
    ..writeln('// GENERATED by tool/generate_actions.dart.')
    ..writeln('// Do not edit by hand.')
    ..writeln();
  for (final g in groups) {
    barrel.writeln("export '${g}_actions.dart';");
  }
  File('lib/src/actions/actions.dart').writeAsStringSync(barrel.toString());
  stdout.writeln('Generated ${catalog.length} actions in '
      '${groups.length} groups.');
}

String _pascal(String snake) =>
    snake.split('_').map((p) => p[0].toUpperCase() + p.substring(1)).join();

// First match wins, so keep specific rules above broad ones.
const _groupRules = <String, String>{
  r'^Action|QuickPresentation|CurrentPresentation|Quiz|Countdown(?!C)|'
      r'F8|F9|F10|AutomaticPresentation|AP(?!I)|FavoriteAction|ApiAction|'
      r'ScriptAction|ModuleAction|RunActions': 'presentation',
  r'Playlist': 'playlists',
  r'Lyrics|Song(?!Group)': 'lyrics',
  r'Text(?!CP|Communication)|Announcement|CustomMessage': 'texts',
  r'Verse|Bible': 'bible',
  r'CP|CommunicationPanel': 'communication_panel',
  r'Audio|Video|Image|File|Media|Thumbnail|Background': 'media',
  r'Settings|Preset|Theme|Logo|Wallpaper|Translation|Transition|NDI|'
      r'Display|Footer|Color': 'settings',
  r'Schedule|Event|Team|Member|Role|Service|History|Histories|Group|Item|'
      r'Favorite|Trigger|Rule': 'planning',
};

String _groupOf(String name) {
  for (final rule in _groupRules.entries) {
    if (RegExp(rule.key).hasMatch(name)) return rule.value;
  }
  return 'system';
}

String _method(_Action a, String name) {
  final out = StringBuffer();
  final desc = a.description.toString();
  if (desc.isNotEmpty) {
    for (final line in _wrap(desc, 74)) {
      out.writeln('  /// $line');
    }
  }
  if (a.since.isNotEmpty) {
    out
      ..writeln('  ///')
      ..writeln('  /// Since Holyrics ${a.since.replaceFirst("v", "")}.');
  }
  final req = a.params.where((p) => !p.optional);
  final opt = a.params.where((p) => p.optional);
  final method = _lowerFirst(name);
  if (a.params.isEmpty) {
    out.writeln("  Future<Object?> $method() => call('$name');");
    return out.toString();
  }
  final sig = [
    for (final p in req) 'required ${p.type} ${_camel(p.wire)}',
    for (final p in opt) '${p.type}? ${_camel(p.wire)}',
  ].join(', ');
  out
    ..writeln('  Future<Object?> $method({$sig}) =>')
    ..writeln("      call('$name', {");
  for (final p in [...req, ...opt]) {
    out.writeln("        '${p.wire}': ${_camel(p.wire)},");
  }
  out.writeln('      });');
  return out.toString();
}

Iterable<String> _wrap(String text, int width) sync* {
  var line = '';
  for (final word in text.split(' ')) {
    if (line.isNotEmpty && line.length + word.length + 1 > width) {
      yield line;
      line = word;
    } else {
      line = line.isEmpty ? word : '$line $word';
    }
  }
  if (line.isNotEmpty) yield line;
}
